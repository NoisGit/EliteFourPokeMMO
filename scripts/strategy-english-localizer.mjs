export const localizeSpanishStrategyToEnglish = (text) => {
  if (typeof text !== 'string') return text

  const translated = replacements.reduce(
    (currentText, [pattern, replacement]) => currentText.replace(pattern, replacement),
    text,
  )

  return grammarReplacements.reduce(
    (currentText, [pattern, replacement]) => currentText.replace(pattern, replacement),
    translated,
  ).trim()
}
